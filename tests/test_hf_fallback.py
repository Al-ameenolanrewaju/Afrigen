def test_get_all_hf_tokens_numbered(monkeypatch):
    """Test token discovery via numbered environment variables (HF_TOKEN_1, HF_TOKEN_2, HF_TOKEN_3)."""
    monkeypatch.setenv("HF_TOKEN_1", "hf_first_token_1111")
    monkeypatch.setenv("HF_TOKEN_2", "hf_second_token_2222")
    monkeypatch.setenv("HF_TOKEN_3", "hf_third_token_3333")
    monkeypatch.delenv("HF_TOKEN", raising=False)
    monkeypatch.delenv("HF_TOKENS", raising=False)

