def test_fallback_account1_fails_account2_succeeds(monkeypatch):
    """When Account 1 fails (e.g. rate limit 429), Account 2 picks up immediately."""
    monkeypatch.setenv("HF_TOKEN_1", "hf_acc_1_failing")
    monkeypatch.setenv("HF_TOKEN_2", "hf_acc_2_working")
    monkeypatch.setenv("HF_TOKEN_3", "hf_acc_3_backup")
    monkeypatch.delenv("HF_TOKEN", raising=False)
    monkeypatch.delenv("HF_TOKENS", raising=False)

    call_log = []

    def dummy_op(token, acc):
        call_log.append(token)
        if token == "hf_acc_1_failing":
            raise RuntimeError("Rate limit hit (HTTP 429)")
        return {"ok": True, "result": "generated by " + acc["name"]}

    result = execute_hf_with_fallback(dummy_op, operation_name="Test Op")
    assert result["ok"] is True
    assert result["result"] == "generated by Account 2"
    assert call_log == ["hf_acc_1_failing", "hf_acc_2_working"]


def test_fallback_account1_and_2_fail_account3_succeeds(monkeypatch):
    """When Account 1 and 2 fail, Account 3 picks up."""
    monkeypatch.setenv("HF_TOKEN_1", "hf_acc_1_error")
    monkeypatch.setenv("HF_TOKEN_2", "hf_acc_2_error")
    monkeypatch.setenv("HF_TOKEN_3", "hf_acc_3_working")
    monkeypatch.delenv("HF_TOKEN", raising=False)
    monkeypatch.delenv("HF_TOKENS", raising=False)

    call_log = []

    def dummy_op(token, acc):
        call_log.append(token)
        if token == "hf_acc_1_error":
            raise RuntimeError("HTTP 401 Unauthorized")
        if token == "hf_acc_2_error":
            return {"ok": False, "error": "Model quota depleted (429)"}
        return {"ok": True, "result": "success on Account 3"}

    result = execute_hf_with_fallback(dummy_op, operation_name="Test Multi-Failover")
    assert result["ok"] is True
    assert result["result"] == "success on Account 3"
    assert call_log == ["hf_acc_1_error", "hf_acc_2_error", "hf_acc_3_working"]


def test_all_accounts_fail(monkeypatch):
    """When all accounts fail, RuntimeError is raised."""
    monkeypatch.setenv("HF_TOKEN_1", "hf_tok_1")
    monkeypatch.setenv("HF_TOKEN_2", "hf_tok_2")
    monkeypatch.setenv("HF_TOKEN_3", "hf_tok_3")
    monkeypatch.delenv("HF_TOKEN", raising=False)
    monkeypatch.delenv("HF_TOKENS", raising=False)

    def failing_op(token, acc):
        raise RuntimeError("Service unavailable 503")

    with pytest.raises(RuntimeError) as exc_info:
        execute_hf_with_fallback(failing_op, operation_name="All Failing")
    assert "All 3 Hugging Face accounts failed" in str(exc_info.value)


def test_cooldown_prioritizes_healthy_accounts(monkeypatch):
    """An account in cooldown is deprioritized so subsequent calls start on a healthy account."""
    monkeypatch.setenv("HF_TOKEN_1", "hf_tok_1")
    monkeypatch.setenv("HF_TOKEN_2", "hf_tok_2")
    monkeypatch.setenv("HF_TOKEN_3", "hf_tok_3")
    monkeypatch.delenv("HF_TOKEN", raising=False)
    monkeypatch.delenv("HF_TOKENS", raising=False)

    # First run: Account 1 fails with 429
    def op1(token, acc):
        if token == "hf_tok_1":
            raise RuntimeError("HTTP 429 Rate limited")
        return {"ok": True}

    execute_hf_with_fallback(op1)

    # Second run: Next call should try Account 2 first because Account 1 is in cooldown
    call_log = []
    def op2(token, acc):
        call_log.append(token)
        return {"ok": True}

    execute_hf_with_fallback(op2)
    assert call_log[0] == "hf_tok_2"


def test_video_generation_with_fallback(monkeypatch):
    """Test generate_social_video failover when first token receives 429."""
    from services.social_creative_hf import generate_social_video

    monkeypatch.setenv("HF_TOKEN_1", "hf_tok_1")
    monkeypatch.setenv("HF_TOKEN_2", "hf_tok_2")
    monkeypatch.delenv("HF_TOKEN", raising=False)
    monkeypatch.delenv("HF_TOKENS", raising=False)

    dummy_mp4 = b"\x00\x00\x00\x20ftypmp42\x00\x00\x00\x00isommp42" + (b"A" * 15000)

    # Mock response: 429 on Account 1, 200 on Account 2
    def mock_requests_post(url, headers=None, **kwargs):
        auth = (headers or {}).get("Authorization", "")
        resp = MagicMock()
        if "hf_tok_1" in auth:
            resp.status_code = 429
            resp.text = "Too many requests"
            return resp
        elif "hf_tok_2" in auth:
            resp.status_code = 200
            resp.content = dummy_mp4
            resp.headers = {"content-type": "video/mp4"}
            return resp
        resp.status_code = 500
        return resp

    with patch("requests.post", side_effect=mock_requests_post):
        res = generate_social_video(prompt="Futuristic Nairobi skyline", duration_seconds=5)
        assert res["ok"] is True
        assert res["provider"] == "huggingface"
        assert res["account_used"] == "Account 2"
        assert res["media_url"].startswith("http")


def test_image_generation_fallback(monkeypatch):
    """Test _generate_image_huggingface failover from Account 1 to Account 2."""
    from services.video import _generate_image_huggingface

    monkeypatch.setenv("HF_TOKEN_1", "hf_acc1_bad")
    monkeypatch.setenv("HF_TOKEN_2", "hf_acc2_good")
    monkeypatch.delenv("HF_TOKEN", raising=False)
    monkeypatch.delenv("HF_TOKENS", raising=False)

    from PIL import Image

    dummy_img = Image.new("RGB", (100, 100), color="blue")

    class MockInferenceClient:
        def __init__(self, token=None, **kwargs):
            self.token = token

        def text_to_image(self, *args, **kwargs):
            if self.token == "hf_acc1_bad":
                raise RuntimeError("429 Client Error: Rate limit reached")
            return dummy_img

    with patch("services.video.InferenceClient", MockInferenceClient), \
         patch("services.video.fal_client.upload_file", return_value="https://cdn.fal.media/test.png"):
        result = _generate_image_huggingface(prompt="African digital art", aspect_ratio="1:1")
        assert result["success"] is True
        assert result["image_url"] == "https://cdn.fal.media/test.png"
        assert result["account_used"] == "Account 2"

